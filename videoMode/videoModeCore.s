/*
 * Fear Campaign custom Uzebox video mode
 *
 * Output:              160x80 2bpp framebuffer only
 * Bitmap output:       160 logical pixels wide, 160 NTSC scanlines
 * Total active:        160 NTSC scanlines
 * Bitmap scaling:      each source row is emitted twice
 * Horizontal timing:   one logical bitmap pixel every 8 AVR clocks
 * Palette:             fixed black/cyan/red/yellow four-color lookup in flash
 *
 * Dual-source presentation:
 *
 *   displayFrameReady == 0
 *      Repeat the most recently completed frame from SPI RAM.
 *
 *   displayFrameReady != 0
 *      Scan the new bitmap directly from AVR SRAM without touching SPI. At the
 *      end of the complete frame, clear displayFrameReady. Foreground then makes
 *      the SPI backing copy after active video has retired.
 *
 * The ready flag is latched exactly once when this full-frame renderer starts.
 * Foreground cannot run while this routine owns the scanlines, so re-checking
 * the flag per line or at frame end would add work without changing semantics.
 *
 * The 2bpp renderer uses four page-aligned 256-byte lookup tables. Each packed
 * byte produces four pixels at exactly eight clocks each, including prefetch and
 * loop overhead. Forty packed bytes span 1280 clocks while horizontal centering
 * and line-tail waits preserve the 1820-cycle scanline cadence.
 */

