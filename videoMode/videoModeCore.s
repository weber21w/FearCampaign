.section .text

.macro SPI_WAIT16 reg
    WAIT \reg, 16
.endm

/* ATmega644 @ F_CPU/2 needs one clock of margin around critical SPDR
 * command/address/read-start transfers. This mirrors the hardware-proven
 * Fear Campaign / kernel spiram.s transaction pacing. */
.macro SPI_WAIT17 reg
    WAIT \reg, 17
.endm

/*
 * Register allocation while the full-frame routine owns r1-r29:
 *   r2  current packed framebuffer byte
 *   r3  prefetched packed framebuffer byte
 *   r4  DAC color
 *   r5  constant zero / SPI dummy byte
 *   r7  duplicate-line parity (0 first line, 1 second line after toggle)
 *   r16 timing temporary
 *   r18 physical scanlines remaining
 *   r19 SPI address low
 *   r20 SPI address middle
 *   r21 SPI address high/bank
 *   r22 packed-byte counter
 *   r23 latched frame-ready state
 *   X   SRAM framebuffer pointer (SRAM path)
 *   Z   2bpp lookup pointer
 */
sub_video_mode:
    clr   r5
    ldi   r18, DISPLAY_SCANLINES
    clr   r7
    ldi   r19, lo8(DISPLAY_BUFFER_ADDR)
    ldi   r20, hi8(DISPLAY_BUFFER_ADDR)
    ldi   r21, DISPLAY_BUFFER_BANK

    /* Latch framebuffer ownership once for the complete 160-line frame. */
    lds   r23, displayFrameReady
    rjmp  .                       /* preserve entry timing */
    ldi   XL, lo8(displayBuffer)
    ldi   XH, hi8(displayBuffer)

    /* Full-frame modes manually own Timer1 for the following scanlines. */
    ldi   r16, (1 << OCF1B) + (1 << OCF1A) + (1 << TOV1)
    sts   _SFR_MEM_ADDR(TIFR1), r16
    clr   r16
    sts   _SFR_MEM_ADDR(TIMSK1), r16
    ldi   r16, (1 << CS10)
    sts   _SFR_MEM_ADDR(TCCR1B), r16

    /* The source selector below is exactly eight clocks on every path. This
     * wait places the first manual HSYNC at the required phase. */
    WAIT  r16, 1317
    rjmp  vm_dispatch_first

/* Exactly eight clocks on both bitmap source paths. */
vm_dispatch_first:
    tst   r23
    breq  vm_dispatch_spi
    nop
    nop
    nop
    nop
    rjmp  vm_nospi_line      /* new frame: SRAM video, absolutely no SPI */
vm_dispatch_spi:
    nop
    nop
    nop
    rjmp  vm_spi_line

/* ======================================================================== */
/* SPI-RAM repeat path: 160 pixels, 2bpp, exactly eight clocks per pixel.     */
/*                                                                            */
/* The 1KB lookup is four page-aligned 256-byte tables. ZL is the packed      */
/* framebuffer byte; incrementing ZH selects the next 2-bit pixel from that   */
/* byte. The next SPI byte is prefetched during pixel 2, so pixel 4 -> the     */
/* next pixel 1 also remains exactly eight clocks including BRNE.             */
/* ======================================================================== */
vm_spi_line:
    rcall hsync_pulse

    cbi   SR_PORT, SR_PIN
    ldi   r16, 0x03              /* sequential read */
    out   SR_DR, r16
    SPI_WAIT17 r16
    out   SR_DR, r21
    SPI_WAIT17 r16
    out   SR_DR, r20
    SPI_WAIT17 r16
    out   SR_DR, r19
    /* addr_lo -> first dummy launch must also clear the 16-clock boundary.
     * WAIT16 + LDI is the hardware-proven 17-clock sequence. */
    SPI_WAIT16 r16
    ldi   r16, 0xFF
    out   SR_DR, r16             /* kernel-compatible first READ dummy */
    SPI_WAIT17 r16

    /* Five safety clocks were added to the READ setup above. Return all five
     * here so first-pixel phase and the 1820-clock scanline stay unchanged. */
    WAIT  r16, (DISPLAY_HCENTER_CYCLES - 2)
    ldi   r22, DISPLAY_STRIDE
    in    r2, SR_DR
    out   SR_DR, r5              /* immediately clock the next packed byte */

vm_spi_next_byte:
    mov   ZL, r2
    ldi   ZH, hi8(vm_2bpp_lut)
    lpm   r4, Z
    out   VIDEO, r4              /* pixel 0 */

vm_spi_after_p0:
    inc   ZH
    lpm   r4, Z
    WAIT  r16, 3
    out   VIDEO, r4              /* pixel 1 */

    inc   ZH
    lpm   r4, Z
    in    r3, SR_DR              /* prefetch next packed byte */
    out   SR_DR, r5
    nop
    out   VIDEO, r4              /* pixel 2 */

    inc   ZH
    dec   r22                    /* flags survive LPM/MOV/NOP/OUT */
    lpm   r4, Z
    mov   r2, r3
    nop
    out   VIDEO, r4              /* pixel 3 */

    brne  vm_spi_next_byte

    /* Final pixel -> blank is also one eight-clock cell. */
    WAIT  r16, 6
    out   VIDEO, r5
    sbi   SR_PORT, SR_PIN

vm_spi_row_done:
    /* Repeat every source row twice. */
    ldi   r16, 1
    eor   r7, r16
    tst   r7
    brne  vm_spi_no_advance
    subi  r19, lo8(-DISPLAY_STRIDE)
    sbci  r20, hi8(-DISPLAY_STRIDE)
    sbci  r21, 0xFF
    rjmp  vm_spi_advance_done
vm_spi_no_advance:
    rjmp  .
    nop
    nop
vm_spi_advance_done:

    dec   r18
    brne  vm_spi_more_lines

    /* Complete the line tail to preserve the 1820-cycle scanline cadence. */
    WAIT  r16, (391 - AUDIO_OUT_HSYNC_CYCLES - DISPLAY_HCENTER_CYCLES)
    rjmp  vm_frame_finish

vm_spi_more_lines:
    WAIT  r16, (401 - AUDIO_OUT_HSYNC_CYCLES - DISPLAY_HCENTER_CYCLES)
    rjmp  vm_spi_line

/* ======================================================================== */
/* No-SPI SRAM path. Newly published frames use this path.                    */
/* The same four-page lookup and eight-clock pixel cadence are used.          */
/* ======================================================================== */
vm_nospi_line:
    rcall hsync_pulse

    /* Match the SPI path's command/address setup timing without touching SPI. */
    rjmp  .
    ldi   r16, 0x02
    nop
    SPI_WAIT17 r16
    nop
    SPI_WAIT17 r16
    nop
    SPI_WAIT17 r16
    nop
    SPI_WAIT17 r16
    WAIT  r16, 17

    /* Cycle-match the five added SPI safety clocks, then pay them back before
     * pixel 0 just like the real SPI path. */
    WAIT  r16, (DISPLAY_HCENTER_CYCLES - 1)
    ldi   r22, DISPLAY_STRIDE
    ld    r2, X+

vm_nospi_next_byte:
    mov   ZL, r2
    ldi   ZH, hi8(vm_2bpp_lut)
    lpm   r4, Z
    out   VIDEO, r4              /* pixel 0 */

vm_nospi_after_p0:
    inc   ZH
    lpm   r4, Z
    WAIT  r16, 3
    out   VIDEO, r4              /* pixel 1 */

    inc   ZH
    lpm   r4, Z
    ld    r3, X+                 /* prefetch next packed byte */
    nop
    out   VIDEO, r4              /* pixel 2 */

    inc   ZH
    dec   r22
    lpm   r4, Z
    mov   r2, r3
    nop
    out   VIDEO, r4              /* pixel 3 */

    brne  vm_nospi_next_byte

    WAIT  r16, 6
    out   VIDEO, r5
    rjmp  .                       /* match two-cycle SPI CS-high timing */

vm_nospi_row_done:
    /* The unconditional prefetch reads byte 41. Back X up one byte so the
     * logical row advance remains exactly DISPLAY_STRIDE (40) bytes. */
    sbiw  r26, 1

    ldi   r16, 1
    eor   r7, r16
    tst   r7
    brne  vm_nospi_no_advance
    subi  r19, lo8(-DISPLAY_STRIDE)
    sbci  r20, hi8(-DISPLAY_STRIDE)
    sbci  r21, 0xFF
    rjmp  vm_nospi_advance_done
vm_nospi_no_advance:
    sbiw  r26, DISPLAY_STRIDE
    rjmp  .
vm_nospi_advance_done:

    dec   r18
    breq  vm_nospi_frame_end

    /* +16 clocks for the narrower active span, -2 for SBIW X,1 above. */
    WAIT  r16, (400 - AUDIO_OUT_HSYNC_CYCLES - DISPLAY_HCENTER_CYCLES)
    rjmp  vm_nospi_line

vm_nospi_frame_end:
    tst   r23
    breq  vm_nospi_not_new
    clr   r16
    sts   displayFrameReady, r16
    /* Preserve the established final-line phase. */
    WAIT  r16, 5
    rjmp  vm_nospi_consumed
vm_nospi_not_new:
    WAIT  r16, 9
vm_nospi_consumed:
    WAIT  r16, (376 - AUDIO_OUT_HSYNC_CYCLES - DISPLAY_HCENTER_CYCLES)
    rjmp  vm_frame_finish

/* ======================================================================== */
/* Cycle-matched final-line handoff.                                        */
/* ======================================================================== */
vm_frame_finish:
    /* Five cycles are charged out of every final-line wait above. This epoch
     * lets foreground code know active scanout has completely retired without
     * altering the hardware-tested 1820-cycle line cadence. */
    lds   r16, displayActiveEpoch
    inc   r16
    sts   displayActiveEpoch, r16
    ldi   r16, hi8(101 - TIMER1_DISPLACE)
    sts   _SFR_MEM_ADDR(TCNT1H), r16
    ldi   r16, lo8(101 - TIMER1_DISPLACE)
    sts   _SFR_MEM_ADDR(TCNT1L), r16
    rcall hsync_pulse

    ldi   r16, (1 << OCF1B) + (1 << OCF1A) + (1 << TOV1)
    sts   _SFR_MEM_ADDR(TIFR1), r16
    ldi   r16, (1 << WGM12) + (1 << CS10)
    sts   _SFR_MEM_ADDR(TCCR1B), r16
    ldi   r16, (1 << OCIE1A)
    sts   _SFR_MEM_ADDR(TIMSK1), r16

    clr   r1
    ret
