/* Fear Campaign: Missile-Command-specific four-channel POKEY inline mixer.
 *
 * Missile Command fixes AUDCTL=$20. pokey.c resolves AUDF/AUDC into prepared
 * timer increments/amplitudes. Channels 1/2 and the high-clock launch channel
 * 3 use a 4096-event POKEY-poly17 window for direct-noise controls; pure/poly5
 * controls retain compact 256-byte pages. The four MODSND IRQ states are
 * precomputed per field, with q1/q2/q3 at V=64/128/192.
 *
 * Both video paths are exactly 216 clocks including RET. Sync edge placement is
 * expressed relative to update_sound entry: HSync rises at internal cycle 127,
 * which is external CBI->SBI cycle 136 after the hsync_pulse caller overhead;
 * pre/post-EQ rises at internal cycle 60, which is external cycle 68. The
 * kernel's compensated video-entry ceiling is 230 clocks.
 */
#include <avr/io.h>
#include <defines.h>

.global update_sound
.global process_music
.extern Pokey_ProcessMusic
.extern pokey_phase
.extern pokey_step
.extern pokey_wave
.extern pokey_amp
.extern pokey_filter
.extern pokey_filter_extra
.extern pokey_noise_page

.macro WAIT reg,clocks
    .if (\clocks) > 767
        ldi \reg, (\clocks)/6
        dec \reg
        jmp .
        brne .-8
        .if ((\clocks) % 6) == 1
            nop
        .elseif ((\clocks) % 6) == 2
            rjmp .
        .elseif ((\clocks) % 6) == 3
            jmp .
        .elseif ((\clocks) % 6) == 4
            rjmp .
            rjmp .
        .elseif ((\clocks) % 6) == 5
            rjmp .
            jmp .
        .endif
    .else
        .if (\clocks) > 2
            ldi \reg, (\clocks)/3
            dec \reg
            brne .-4
        .endif
        .rept (\clocks) % 3
            nop
        .endr
    .endif
.endm


/* Channels 1/2: 35 clocks. phase is Q8.8 timer-event position. For direct
 * poly17 (odd wave selector), the high phase byte is the low eight bits of a
 * 12-bit event index and pokey_noise_page supplies bits 8..11. Carry out of
 * the Q8.8 accumulator advances that page. Pure/poly5 use compact page LUTs;
 * their path is padded to exactly the same 35 clocks. */
.macro MIX_LONG_CH phaseoff, stepoff, waveoff, ampoff, pageoff
    lds   r16, pokey_phase+\phaseoff
    lds   r17, pokey_phase+\phaseoff+1
    lds   r18, pokey_step+\stepoff
    lds   ZH,  pokey_step+\stepoff+1
    add   r16, r18
    adc   r17, ZH
    sts   pokey_phase+\phaseoff, r16
    sts   pokey_phase+\phaseoff+1, r17
    lds   r18, pokey_wave+\waveoff
    sbrc  r18, 0
    rjmp  pokey_long_noise_\@
    mov   ZL, r17
    ldi   ZH, hi8(pokey_wave_base)
    add   ZH, r18
    lpm   r16, Z
    WAIT  r18, 4
    rjmp  pokey_long_done_\@
pokey_long_noise_\@:
    lds   ZH, pokey_noise_page+\pageoff
    adc   ZH, r1
    andi  ZH, 0x0f
    sts   pokey_noise_page+\pageoff, ZH
    mov   ZL, r17
    subi  ZH, hi8(-(pokey_poly17_long))
    lpm   r16, Z
pokey_long_done_\@:
    lds   r18, pokey_amp+\ampoff
    sbrc  r16, 7
    neg   r18
    add   r0, r18
.endm

/* Channel 3: 30 clocks. Missile Command dedicates this high-clock voice to
 * SABLAU direct-poly17. phase.lo is fractional timer events, phase.hi is the
 * low event-index byte, and pokey_noise_page[2] supplies the upper four bits. */
.macro MIX_LONG_CH3
    lds   r16, pokey_phase+4
    lds   r17, pokey_phase+5
    lds   r18, pokey_step+4
    lds   ZH,  pokey_step+5
    add   r16, r18
    adc   r17, ZH
    lds   ZH,  pokey_noise_page+2
    adc   ZH, r1
    andi  ZH, 0x0f
    sts   pokey_noise_page+2, ZH
    sts   pokey_phase+4, r16
    sts   pokey_phase+5, r17
    mov   ZL, r17
    subi  ZH, hi8(-(pokey_poly17_long))
    lpm   r16, Z
    lds   r18, pokey_amp+2
    sbrc  r16, 7
    neg   r18
    add   r0, r18
.endm

/* Channel 4 never uses direct poly17 in Missile Command's sound tables. */
.macro MIX_CH4
    lds   r16, pokey_phase+6
    lds   r17, pokey_phase+7
    lds   r18, pokey_step+6
    lds   ZH,  pokey_step+7
    add   r16, r18
    adc   r17, ZH
    sts   pokey_phase+6, r16
    sts   pokey_phase+7, r17
    mov   ZL, r17
    lds   r18, pokey_wave+3
    ldi   ZH, hi8(pokey_wave_base)
    add   ZH, r18
    lpm   r16, Z
    lds   r18, pokey_amp+3
    sbrc  r16, 7
    neg   r18
    add   r0, r18
.endm

.section .text
/* The stock video core calls process_music once per VSYNC. Tail-call the
 * C wrapper, which advances four original Missile Command sound IRQ ticks;
 * its RET returns directly to the kernel. */
process_music:
    jmp Pokey_ProcessMusic

/* In: ZL = stock Uzebox video phase.
 * Fixed prologue = 11 clocks before the phase branch; ch1/ch2=35, ch3=30, ch4=27, RC tail=45.
 * HSync: SBI begins at internal cycle 127 (external CBI->SBI cycle 136);
 * ch4 runs after the edge. Total 216.
 * non-HSync: short SBI begins at internal cycle 60 (external cycle 68), with
 * the common post-short-sync merge retained at internal cycle 70. Total 216.
 */
update_sound:
    push  r16
    push  r17
    push  r18
    push  r19
    mov   r19, ZL
    ldi   r16, 0x80
    mov   r0, r16
    sbrs  r19, 1
    rjmp  pokey_non_hsync

    /* HSync caller spends 9 clocks from the start of CBI to update_sound.
     * Therefore SBI must BEGIN at internal cycle 127 to reproduce the stock
     * 136-clock external low pulse. Seven clocks moved after the edge keep the
     * complete mixer at 216 clocks. */
    MIX_LONG_CH 0, 0, 0, 0, 0
    MIX_LONG_CH 2, 2, 1, 1, 1
    MIX_LONG_CH3
    WAIT  r16, 14
    sbi   _SFR_IO_ADDR(SYNC_PORT), SYNC_PIN
    /* Move channel 4 after the video-critical edge to preserve its phase. */
    MIX_CH4
    WAIT  r16, 13
    rjmp  pokey_output

pokey_non_hsync:
    MIX_LONG_CH 0, 0, 0, 0, 0
    /* Pre/post equalization caller spends 8 clocks from CBI to mixer entry.
     * Stock Uzebox therefore begins SBI at internal cycle 60 for the 68-clock
     * external short pulse. Keep the no-short/common merge at cycle 70. */
    sbrs  r19, 0
    rjmp  pokey_no_short
    WAIT  r16, 9
    sbi   _SFR_IO_ADDR(SYNC_PORT), SYNC_PIN
    WAIT  r16, 6
    rjmp  pokey_after_short
pokey_no_short:
    WAIT  r16, 18
pokey_after_short:
    MIX_LONG_CH 2, 2, 1, 1, 1
    MIX_LONG_CH3
    MIX_CH4
    WAIT  r16, 9

pokey_output:
    /* Q8.8 adaptive cabinet RC. Base /4 is followed by zero, one, or two
     * extra arithmetic shifts. Each optional block is exactly 6 clocks,
     * so /4, /8 and /16 all retain identical HSYNC timing. */
    lds   ZL,  pokey_filter+0
    lds   ZH,  pokey_filter+1
    clr   r18
    sub   r18, ZL
    mov   r16, r0
    sbc   r16, ZH
    asr   r16
    ror   r18
    asr   r16
    ror   r18
    lds   r19, pokey_filter_extra
    sbrs  r19, 0
    rjmp  pokey_filter_no3
    asr   r16
    ror   r18
    rjmp  pokey_filter_after3
pokey_filter_no3:
    nop
    nop
    nop
pokey_filter_after3:
    sbrs  r19, 1
    rjmp  pokey_filter_no4
    asr   r16
    ror   r18
    rjmp  pokey_filter_after4
pokey_filter_no4:
    nop
    nop
    nop
pokey_filter_after4:
    add   ZL,  r18
    adc   ZH,  r16
    sts   pokey_filter+0, ZL
    sts   pokey_filter+1, ZH
    mov   r0, ZH
    sts   _SFR_MEM_ADDR(OCR2A), r0
    pop   r19
    pop   r18
    pop   r17
    pop   r16
    ret

